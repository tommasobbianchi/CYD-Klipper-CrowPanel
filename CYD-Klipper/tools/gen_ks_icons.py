#!/usr/bin/env python3
"""Rasterise Sovol/KlipperScreen z-bolt SVG icons into LVGL 8 A8 (alpha-only) images, one bitmap per size.

usage: gen_ks_icons.py <KlipperScreen/styles/z-bolt/images> <out_dir>  -> out_dir/icons.cpp + icons.h
Icons are alpha masks; the UI recolours them with lv_obj_set_style_img_recolor(). LVGL's runtime zoom of
A8 images is unreliable, so every size the UI uses is rendered exactly (ks_icon(name, px) picks the smallest >= px).
"""
import subprocess, sys, tempfile, pathlib, re
from PIL import Image

SIZES = [40, 56, 72]            # title bar / action bar + small buttons / menu buttons
EXTRA = {"klipper": [128]}      # splash logo
src, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
table, body, colored, dark = [], [], [], []

def raster(svg_text, tmp, stem, size):
    tsvg = pathlib.Path(tmp) / f"{stem}.svg"
    png = pathlib.Path(tmp) / f"{stem}_{size}.png"
    tsvg.write_text(svg_text)
    subprocess.run(["convert", "-background", "none", "-density", "512", str(tsvg), "-resize", f"{size}x{size}",
                    "-gravity", "center", "-extent", f"{size}x{size}", str(png)], check=True, stderr=subprocess.DEVNULL)
    return Image.open(png).convert("RGBA")

with tempfile.TemporaryDirectory() as tmp:
    for svg in sorted(src.glob("*.svg")):
        # a few icons (spool) tint through a CSS variable at runtime; flatten it to white, LVGL recolours anyway
        text = re.sub(r"var\([^)]*\)", "#ffffff", svg.read_text())
        base = "ks_ic_" + re.sub(r"\W", "_", svg.stem.replace("+", "_plus").replace("-", "_"))
        entries = []
        for size in SIZES + EXTRA.get(svg.stem, []):
            im = raster(text, tmp, svg.stem, size)
            px = im.load()
            if size == SIZES[-1]:   # flag icons whose visible pixels are not near-monochrome (colour would be lost)
                if any(px[x, y][3] > 64 and max(px[x, y][:3]) - min(px[x, y][:3]) > 60
                       for y in range(size) for x in range(size)):
                    colored.append(svg.stem)
            # icons are white glyphs with black detail on transparent: keep the detail by weighting alpha with luminance
            # (icons with no white pixel at all, i.e. pure black glyphs, keep plain alpha so they do not vanish)
            opaque = [px[x, y] for y in range(size) for x in range(size) if px[x, y][3] > 64]
            light = any(0.299 * r + 0.587 * g + 0.114 * b > 150 for r, g, b, a in opaque)   # has a white part -> it is the glyph
            if not light: dark.append(svg.stem) if svg.stem not in dark else None
            def lum(p): return (0.299 * p[0] + 0.587 * p[1] + 0.114 * p[2]) / 255
            alpha = bytes(int(px[x, y][3] * (lum(px[x, y]) if light else 1)) for y in range(size) for x in range(size))
            ident = f"{base}_{size}"
            body.append(f"static const uint8_t {ident}_map[] = {{" + ",".join(map(str, alpha)) + "};\n"
                        f"static const lv_img_dsc_t {ident} = {{{{LV_IMG_CF_ALPHA_8BIT,0,0,{size},{size}}},{len(alpha)},{ident}_map}};\n")
            entries.append((size, ident))
        table.append((svg.stem, entries))

out.mkdir(parents=True, exist_ok=True)
rows = "".join('  {"%s", {%s}},\n' % (n, ", ".join("{%d, &%s}" % (s, i) for s, i in e)) for n, e in table)
(out / "icons.cpp").write_text(
    '// generated by tools/gen_ks_icons.py from KlipperScreen z-bolt icons (AGPL-3.0)\n#include "icons.h"\n#include <string.h>\n'
    + "".join(body)
    + "struct ks_icon_size { int px; const lv_img_dsc_t* img; };\n"
      "struct ks_icon_entry { const char* name; ks_icon_size sizes[4]; };\n"
      "static const ks_icon_entry ks_icon_table[] = {\n" + rows + "  {nullptr, {}}\n};\n"
      "const lv_img_dsc_t* ks_icon(const char* name, int px) {\n"
      "  for (const ks_icon_entry* e = ks_icon_table; e->name; e++) {\n"
      "    if (strcmp(e->name, name)) continue;\n"
      "    const lv_img_dsc_t* best = nullptr;\n"
      "    for (const ks_icon_size& s : e->sizes) { if (!s.img) break; best = s.img; if (s.px >= px) break; }\n"
      "    return best;\n"
      "  }\n  return nullptr;\n}\n")
(out / "icons.h").write_text('#pragma once\n#include "lvgl.h"\n'
                             "// KlipperScreen icon by name (e.g. \"move\"); smallest rendered size >= px, nullptr if unknown\n"
                             "const lv_img_dsc_t* ks_icon(const char* name, int px);\n")
print(f"{len(table)} icons x sizes {SIZES}; non-monochrome (colour lost): {sorted(set(colored)) or 'none'}; dark glyphs (alpha only): {sorted(set(dark)) or 'none'}")
