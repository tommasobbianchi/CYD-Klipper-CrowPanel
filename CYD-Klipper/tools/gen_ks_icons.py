#!/usr/bin/env python3
"""Rasterise Sovol/KlipperScreen z-bolt SVG icons into LVGL 8 A8 (alpha-only) images.

usage: gen_ks_icons.py <KlipperScreen/styles/z-bolt/images> <out_dir>  -> out_dir/icons.cpp + icons.h
Icons are alpha masks; the UI recolours them with lv_obj_set_style_img_recolor().
"""
import subprocess, sys, tempfile, pathlib, re
from PIL import Image

SIZE = 80
src, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
names, body, colored = [], [], []

with tempfile.TemporaryDirectory() as tmp:
    for svg in sorted(src.glob("*.svg")):
        png = pathlib.Path(tmp) / (svg.stem + ".png")
        tsvg = pathlib.Path(tmp) / (svg.stem + ".svg")
        # a few icons (spool) tint through a CSS variable at runtime; flatten it to white, LVGL recolours anyway
        tsvg.write_text(re.sub(r"var\([^)]*\)", "#ffffff", svg.read_text()))
        subprocess.run(["convert", "-background", "none", "-density", "512", str(tsvg),
                        "-resize", f"{SIZE}x{SIZE}", "-gravity", "center", "-extent", f"{SIZE}x{SIZE}", str(png)],
                       check=True, stderr=subprocess.DEVNULL)
        im = Image.open(png).convert("RGBA")
        px = im.load()
        # flag icons whose visible pixels are not near-monochrome (alpha-only would lose their colour)
        for y in range(SIZE):
            for x in range(SIZE):
                r, g, b, a = px[x, y]
                if a > 64 and max(r, g, b) - min(r, g, b) > 60:
                    colored.append(svg.stem); break
            else:
                continue
            break
        alpha = bytes(px[x, y][3] for y in range(SIZE) for x in range(SIZE))
        ident = "ks_ic_" + re.sub(r"\W", "_", svg.stem.replace("+", "_plus").replace("-", "_"))
        names.append((svg.stem, ident))
        body.append(f"static const uint8_t {ident}_map[] = {{" + ",".join(map(str, alpha)) + "};\n"
                    f"const lv_img_dsc_t {ident} = {{{{LV_IMG_CF_ALPHA_8BIT,0,0,{SIZE},{SIZE}}},{len(alpha)},{ident}_map}};\n")

out.mkdir(parents=True, exist_ok=True)
(out / "icons.cpp").write_text('// generated by tools/gen_ks_icons.py from KlipperScreen z-bolt icons (AGPL-3.0)\n'
                               '#include "icons.h"\n' + "".join(body) +
                               "const ks_icon_entry ks_icon_table[] = {\n" +
                               "".join(f'  {{"{n}", &{i}}},\n' for n, i in names) + "  {nullptr, nullptr}\n};\n"
                               "#include <string.h>\n"
                               "const lv_img_dsc_t* ks_icon(const char* name) {\n"
                               "  for (const ks_icon_entry* e = ks_icon_table; e->name; e++) if (!strcmp(e->name, name)) return e->img;\n"
                               "  return nullptr;\n}\n")
(out / "icons.h").write_text('#pragma once\n#include "lvgl.h"\n'
                             "struct ks_icon_entry { const char* name; const lv_img_dsc_t* img; };\n"
                             "extern const ks_icon_entry ks_icon_table[];\n"
                             "const lv_img_dsc_t* ks_icon(const char* name);  // KlipperScreen icon name, e.g. \"move\"; nullptr if unknown\n"
                             + "".join(f"extern const lv_img_dsc_t {i};\n" for _, i in names))
print(f"{len(names)} icons, {SIZE}x{SIZE} A8; non-monochrome (colour lost): {sorted(set(colored)) or 'none'}")
